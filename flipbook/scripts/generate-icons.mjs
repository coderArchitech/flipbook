// Regenerates shared/icons.mjs from the pinned lucide-react package.
// Every icon element becomes plain SVG path data so the HTML renderer and
// PDFKit draw identical strokes. Run: node scripts/generate-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "heart", "star", "leaf", "sun", "moon", "sparkles", "gift", "tag",
  "shopping-bag", "shopping-cart", "truck", "package", "phone", "mail",
  "map-pin", "globe", "clock", "calendar", "check", "circle-check", "x",
  "plus", "minus", "arrow-right", "arrow-left", "arrow-up-right",
  "chevron-right", "info", "award", "badge-percent", "percent", "flame",
  "droplet", "flower", "coffee", "utensils", "camera", "music", "play",
  "house", "user", "users", "thumbs-up", "shield-check", "recycle", "zap",
  "smile",
];
const n = (v) => Number(v ?? 0);
const arc = (cx, cy, rx, ry) =>
  `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0Z`;
function toPath([tag, a]) {
  if (tag === "path") return a.d;
  if (tag === "circle") return arc(n(a.cx), n(a.cy), n(a.r), n(a.r));
  if (tag === "ellipse") return arc(n(a.cx), n(a.cy), n(a.rx), n(a.ry));
  if (tag === "line") return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
  if (tag === "polyline" || tag === "polygon") {
    const p = a.points.trim().split(/[\s,]+/).map(Number);
    let d = `M${p[0]} ${p[1]}`;
    for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
    return tag === "polygon" ? d + "Z" : d;
  }
  if (tag === "rect") {
    const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height);
    const r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2);
    if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
    return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
  }
  throw Error("Unsupported icon element " + tag);
}
const icons = {};
for (const name of NAMES) {
  const source = readFileSync(
    new URL(`../node_modules/lucide-react/dist/esm/icons/${name}.js`, import.meta.url),
    "utf8",
  );
  const literal = source.match(/createLucideIcon\("[^"]+", (\[[\s\S]*\])\);/)[1];
  icons[name] = Function(`return ${literal}`)().map(toPath);
}
const version = JSON.parse(
  readFileSync(new URL("../node_modules/lucide-react/package.json", import.meta.url)),
).version;
writeFileSync(
  new URL("../shared/icons.mjs", import.meta.url),
  `// Generated by scripts/generate-icons.mjs from lucide-react ${version}.
// Lucide icons are ISC licensed: https://lucide.dev/license
// Each icon is a list of SVG path strings on a 24 x 24 stroked grid.
export const ICONS = Object.freeze(${JSON.stringify(icons, null, 1)});
export const ICON_NAMES = Object.freeze(Object.keys(ICONS));
`,
);
console.log(`Wrote ${NAMES.length} icons.`);
